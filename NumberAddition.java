//WAJP TO ADD 2 NUMBERS
class NumberAddition{
	public static void main(String args[]){
		int number1 = 5;
		int number2 = 6;
		
		System.out.println("Sum is "+number1 + number2);
		//output is 56
		System.out.println("Sum is "+(number1 + number2));
		//output is 11
		System.out.println(number1+number2+ "Sum is "+(number1 + number2));
		//output is 11 sum is 11
		int a=0627;//decimal form literal
		System.out.println(a);
		int b=0b1111;//binary literal
		System.out.println(b);
		int c=0xFace;//hexadecimal literal
		System.out.println(c);
		int d= 0100;//octal form literal
		
		System.out.println(d);
		//+ is used for concatenation of strings.
	}
}